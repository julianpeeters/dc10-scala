        case t@`Type.Lam: llx_xl_x_xl_x`(lvl, _, _) => t.copy(lvl = lvl + 1)
        case t@`Type.Var: llx_xl_x_xl_x`(lvl, _, _) => t.copy(lvl = lvl + 1)
        case t@`Type.Lam: x_x_x`(lvl, _, _, _) => t.copy(lvl = lvl + 1)
        case t@`Type.Var: x_x_x`(lvl, _, _) => t.copy(lvl = lvl + 1)
        case t@`Type.Lam: lx_xl_x_x`(lvl, _, _, _) => t.copy(lvl = lvl + 1)
        case t@`Type.Var: lx_xl_x_x`(lvl, _, _) => t.copy(lvl = lvl + 1)
        // case t@`Type.Lam: x_x_x_x`(lvl, domain1, domain2, domain3, codomain) => t.copy(lvl = lvl + 1)
        // case t@`Type.Var: x_x_x_x`(lvl, _, _) => t.copy(lvl = lvl + 1)
        // case t@`Type.Lam: lx_xl_x_x_x`(lvl, domain1, domain2, domain3, codomain) => t.copy(lvl = lvl + 1)
        // case t@`Type.Var: lx_xl_x_x_x`(lvl, _, _) => t.copy(lvl = lvl + 1)
        // case t@`Type.Lam: x_x_x_x_x`(lvl, domain1, domain2, domain3, domain4, codomain) => t.copy(lvl = lvl + 1)
        // case t@`Type.Var: x_x_x_x_x`(lvl, _, _) => t.copy(lvl = lvl + 1)
        // case t@`Type.Lam: lx_xl_x_x_x_x`(lvl, _, _, _, _, _) =>  t.copy(lvl = lvl + 1)
        // case t@`Type.Var: lx_xl_x_x_x_x`(lvl, _, _) => t.copy(lvl = lvl + 1)
