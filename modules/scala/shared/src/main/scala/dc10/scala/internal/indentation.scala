package dc10.scala.internal

import dc10.scala.*

object indentation:

  extension (statement: Statement)
    def addIndent: Statement =
      statement match
        case s@CaseDef(lambda) => s
        case s@CaseClassDef(tpe, _, _) => s.copy(tpe = tpe.copy(lvl = tpe.lvl + 1))
        case s@LibDep(_, _, _) => s
        case s@PackageDef(_, _) => s
        case s@`DefDef: x`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
        case s@`DefDef: x_x x`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
        case s@`DefDef: x_x_x x x`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
        case s@ObjDef(obj) => s.copy(obj = obj.copy(lvl = obj.lvl + 1, body = obj.body.map(s => s.addIndent)))
        case s@`SealedTraitDef: x`(tpe) => s.copy(tpe = tpe.copy(lvl = tpe.lvl + 1))
        case s@`TraitDef: x`(tpe) => s.copy(tpe = tpe.copy(lvl = tpe.lvl + 1))
        case s@`TraitDef: x_x`(tpe, _, body) => s.copy(tpe = tpe.copy(lvl = tpe.lvl + 1), body = s.body.map(s => s.addIndent))
        case s@`TypeDef: x`(tpe) => s.copy(tpe = tpe.copy(lvl = tpe.lvl + 1))
        case s@`TypeDef: x_x x`(tpe) => s.copy(tpe = tpe.copy(lvl = tpe.lvl + 1))
        case s@`ValDef: x`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
        case s@`ValDef: x_x x`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
        case s@`ValDef: x_x llx_xl_x_x x_x xl`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
        case s@`ValDef: x_x_x x x`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
        case s@`ValDef: x_x_x x llx_xl_x_x x_x xl`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
        case s@`ValDef: x_x_x x lx_x llx_xl_x_x x_x xll`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
        case s@`ValDef: lx_xl_x_x x_x x`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
        case s@`ValDef: lx_xl_x_x x_x llx_xl_x x_xl`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
        case s@`GivenDef: x`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
        case s@`GivenDef: x_x x`(value) => s.copy(value = value.copy(lvl = value.lvl + 1))
      
  extension (tpe: Type)
