        case t@`Type.App: x_x x`(lvl, _, _) => t.copy(lvl = lvl + 1)
        case t@`Type.Var: x_x x`(lvl, _, _, _) => t.copy(lvl = lvl + 1)
        case t@`Type.App: lx_xl_x x_x`(lvl, _, _) => t.copy(lvl = lvl + 1)
        case t@`Type.Var: lx_xl_x x_x`(lvl, _, _, _) => t.copy(lvl = lvl + 1)
