        case t@`Type.Var: llx_xl_x_xl_x lx_xl_x_x`(lvl, _, _, _) => t.copy(lvl = lvl + 1)
        case t@`Type.App: x_x_x x x`(lvl, _, _, _) => t.copy(lvl = lvl + 1)
        case t@`Type.AppInfix: x_x_x x x`(lvl, _, _, _) => t.copy(lvl = lvl + 1)
        case t@`Type.Var: x_x_x x x`(lvl, _, _, _, _) => t.copy(lvl = lvl + 1)
        case t@`Type.AppInfix: x_x_x x lx_x xl`(lvl, _, _, _) => t.copy(lvl = lvl + 1)
